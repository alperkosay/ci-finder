export const locales: Record<string, Messages> = { en, tr };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function createTranslator(locale: string, overrides?: Partial<Messages>): Translate {
  const base = locales[locale] ?? locales[locale.split("-")[0]!] ?? en;
  const messages = { ...en, ...base, ...overrides };
  return (key, vars) => {
    let s: string = messages[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}
